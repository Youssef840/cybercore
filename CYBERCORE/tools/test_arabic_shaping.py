# Faithful Python port of src/ui/ArabicText.cpp shaping, validated against the
# well-known `arabic_reshaper` library. If the logical presentation-forms match
# for every test word, the C++ shaping table + joining rules are correct.
import arabic_reshaper

# (iso, fin, ini, med, dual) for U+0621..U+064A ; 0 = no form
F = {
0x0621:(0xFE80,0,0,0,False),0x0622:(0xFE81,0xFE82,0,0,False),0x0623:(0xFE83,0xFE84,0,0,False),
0x0624:(0xFE85,0xFE86,0,0,False),0x0625:(0xFE87,0xFE88,0,0,False),0x0626:(0xFE89,0xFE8A,0xFE8B,0xFE8C,True),
0x0627:(0xFE8D,0xFE8E,0,0,False),0x0628:(0xFE8F,0xFE90,0xFE91,0xFE92,True),0x0629:(0xFE93,0xFE94,0,0,False),
0x062A:(0xFE95,0xFE96,0xFE97,0xFE98,True),0x062B:(0xFE99,0xFE9A,0xFE9B,0xFE9C,True),0x062C:(0xFE9D,0xFE9E,0xFE9F,0xFEA0,True),
0x062D:(0xFEA1,0xFEA2,0xFEA3,0xFEA4,True),0x062E:(0xFEA5,0xFEA6,0xFEA7,0xFEA8,True),0x062F:(0xFEA9,0xFEAA,0,0,False),
0x0630:(0xFEAB,0xFEAC,0,0,False),0x0631:(0xFEAD,0xFEAE,0,0,False),0x0632:(0xFEAF,0xFEB0,0,0,False),
0x0633:(0xFEB1,0xFEB2,0xFEB3,0xFEB4,True),0x0634:(0xFEB5,0xFEB6,0xFEB7,0xFEB8,True),0x0635:(0xFEB9,0xFEBA,0xFEBB,0xFEBC,True),
0x0636:(0xFEBD,0xFEBE,0xFEBF,0xFEC0,True),0x0637:(0xFEC1,0xFEC2,0xFEC3,0xFEC4,True),0x0638:(0xFEC5,0xFEC6,0xFEC7,0xFEC8,True),
0x0639:(0xFEC9,0xFECA,0xFECB,0xFECC,True),0x063A:(0xFECD,0xFECE,0xFECF,0xFED0,True),0x0641:(0xFED1,0xFED2,0xFED3,0xFED4,True),
0x0642:(0xFED5,0xFED6,0xFED7,0xFED8,True),0x0643:(0xFED9,0xFEDA,0xFEDB,0xFEDC,True),0x0644:(0xFEDD,0xFEDE,0xFEDF,0xFEE0,True),
0x0645:(0xFEE1,0xFEE2,0xFEE3,0xFEE4,True),0x0646:(0xFEE5,0xFEE6,0xFEE7,0xFEE8,True),0x0647:(0xFEE9,0xFEEA,0xFEEB,0xFEEC,True),
0x0648:(0xFEED,0xFEEE,0,0,False),0x0649:(0xFEEF,0xFEF0,0,0,False),0x064A:(0xFEF1,0xFEF2,0xFEF3,0xFEF4,True),
}
LAMALEF={0x0622:(0xFEF5,0xFEF6),0x0623:(0xFEF7,0xFEF8),0x0625:(0xFEF9,0xFEFA),0x0627:(0xFEFB,0xFEFC)}

def joins_prev(cp): return cp in F and cp!=0x0621
def joins_next(cp): return cp in F and F[cp][4]
def transparent(cp): return 0x064B<=cp<=0x065F or cp in (0x0640,0x0670)

def shape_logical(s):
    cps=[ord(c) for c in s if not transparent(ord(c))]
    out=[]; k=0; n=len(cps)
    while k<n:
        c=cps[k]
        if c not in F: out.append(c); k+=1; continue
        if c==0x0644 and k+1<n and cps[k+1] in LAMALEF:
            pj = k>0 and joins_next(cps[k-1])
            out.append(LAMALEF[cps[k+1]][1 if pj else 0]); k+=2; continue
        iso,fin,ini,med,dual=F[c]
        pj = k>0 and joins_next(cps[k-1])
        nj = dual and k+1<n and joins_prev(cps[k+1])
        g = med if (pj and nj) else fin if pj else ini if nj else iso
        out.append(g or iso); k+=1
    return out

tests=["مرحبا","السلام عليكم","لا","الله","كتاب","بلوتوث","شبكة","إعدادات","فحص","القائمة","يمين","محمد","ملف","لأن"]
ok=True
for w in tests:
    mine=shape_logical(w)
    ref=[ord(c) for c in arabic_reshaper.reshape(w)]
    # arabic_reshaper keeps spaces; align by filtering spaces from both
    minef=[g for g in mine if g!=0x20]
    reff=[g for g in ref if g!=0x20]
    match = minef==reff
    ok = ok and match
    print(("PASS" if match else "FAIL"), w, "->", " ".join(f"{g:04X}" for g in mine))
    if not match:
        print("   ref:", " ".join(f"{g:04X}" for g in ref))
print("\nALL PASS" if ok else "\nSOME FAILED")
